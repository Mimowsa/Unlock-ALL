import { spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const action = process.argv[2];
if (
  !["start", "stop"].includes(action) ||
  process.env.NODE_ENV === "production"
)
  throw new Error("Use start or stop in a local development environment.");
const metadataFile = resolve(".local/postgres.json");
function command(name, args, options = {}) {
  const executable = process.env.PG_BIN ? join(process.env.PG_BIN, name) : name;
  const result = spawnSync(executable, args, { encoding: "utf8", ...options });
  if (result.error)
    throw new Error(
      `Cannot run ${name}. Install PostgreSQL 14+ or set PG_BIN to its bin directory.`,
    );
  if (result.status !== 0 && !options.allowFailure)
    throw new Error(
      `${name} failed: ${(result.stderr || result.stdout).trim()}`,
    );
  return result;
}
let metadata;
if (existsSync(metadataFile)) {
  metadata = JSON.parse(readFileSync(metadataFile, "utf8"));
  if (
    metadata.version !== 1 ||
    metadata.role !== "unlock_all" ||
    metadata.database !== "unlock_all_demo" ||
    !metadata.dataDirectory.startsWith(join(tmpdir(), "unlock-all-pg-")) ||
    !Number.isInteger(metadata.port) ||
    metadata.port < 1024 ||
    metadata.port > 65535
  )
    throw new Error("Invalid local database metadata.");
}
if (action === "stop") {
  if (!metadata || !existsSync(metadata.dataDirectory)) {
    console.log("No project-owned local cluster to stop.");
    process.exit(0);
  }
  if (
    command("pg_ctl", ["-D", metadata.dataDirectory, "status"], {
      allowFailure: true,
    }).status !== 0
  ) {
    console.log("Project-owned PostgreSQL is already stopped.");
    process.exit(0);
  }
  command("pg_ctl", ["-D", metadata.dataDirectory, "-m", "fast", "-w", "stop"]);
  console.log("Project-owned PostgreSQL stopped; data preserved.");
  process.exit(0);
}
if (!metadata) {
  const port = Number(process.env.UNLOCK_ALL_PG_PORT || 55432);
  if (!Number.isInteger(port) || port < 1024 || port > 65535)
    throw new Error("UNLOCK_ALL_PG_PORT must be between 1024 and 65535.");
  const dataDirectory = mkdtempSync(join(tmpdir(), "unlock-all-pg-"));
  command("initdb", [
    "-D",
    dataDirectory,
    "-U",
    "unlock_all",
    "-A",
    "trust",
    "--encoding=UTF8",
    "--no-locale",
  ]);
  metadata = {
    version: 1,
    dataDirectory,
    role: "unlock_all",
    database: "unlock_all_demo",
    port,
  };
  mkdirSync(".local", { recursive: true, mode: 0o700 });
  writeFileSync(metadataFile, JSON.stringify(metadata, null, 2), {
    mode: 0o600,
    flag: "wx",
  });
}
if (!existsSync(join(metadata.dataDirectory, "PG_VERSION")))
  throw new Error(
    "The temporary cluster is missing. Restore it or move .local/postgres.json aside to create a fresh demo cluster. No data was deleted.",
  );
if (
  command("pg_ctl", ["-D", metadata.dataDirectory, "status"], {
    allowFailure: true,
  }).status !== 0
)
  command("pg_ctl", [
    "-D",
    metadata.dataDirectory,
    "-l",
    join(metadata.dataDirectory, "server.log"),
    "-o",
    `-h 127.0.0.1 -p ${metadata.port} -k ${metadata.dataDirectory}`,
    "-w",
    "start",
  ]);
const args = [
  "-h",
  "127.0.0.1",
  "-p",
  String(metadata.port),
  "-U",
  metadata.role,
];
const found = command("psql", [
  ...args,
  "-X",
  "-w",
  "-d",
  "postgres",
  "-Atc",
  "SELECT 1 FROM pg_database WHERE datname = 'unlock_all_demo'",
]);
if (!found.stdout.trim()) command("createdb", [...args, metadata.database]);
if (!existsSync(".env")) {
  const url = `postgresql://${metadata.role}@127.0.0.1:${metadata.port}/${metadata.database}`;
  writeFileSync(
    ".env",
    `# Local development only. Generated by db:local:start; never commit.\nDATABASE_URL="${url}"\nDIRECT_URL="${url}"\nAPP_MODE=demo\nDEMO_SEED_ENABLED=true\nDEMO_CHECKOUT_ENABLED=false\nACTIVATION_KEY_KEY_ID=local-v1\nACTIVATION_KEY_ENCRYPTION_KEY=${randomBytes(32).toString("hex")}\nACTIVATION_KEY_FINGERPRINT_SECRET=${randomBytes(32).toString("hex")}\n`,
    { mode: 0o600, flag: "wx" },
  );
  console.log(
    "Private .env generated with independent local encryption secrets.",
  );
} else
  console.log(
    "Existing .env preserved. Check that it targets this cluster before running migrations.",
  );
console.log(
  `Project-owned PostgreSQL ready on 127.0.0.1:${metadata.port}, database unlock_all_demo.`,
);
console.log(
  "This loopback-only cluster uses trust authentication for fictional local data. Its data directory is temporary; back up the database and secrets before cleaning system temporary files.",
);
